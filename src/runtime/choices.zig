//! Current choices and the thread each was generated in.
//!
//! ink's ProcessChoice stores `threadAtGeneration = callStack.ForkThread()` in every choice:
//! a copy of the current thread with a new thread counter. Choosing a choice makes that copy
//! the only thread. A choice keeps its own counter, but the frames and temps of consecutive
//! choices are nearly always identical (a menu in one weave), so an identical copy is stored
//! once and shared. The snapshot area is cleared with the choices.

const std = @import("std");
const assert = std.debug.assert;
const limits = @import("../core/limits.zig");
const fault = @import("../core/fault.zig");
const BoundedStack = @import("../core/bounded_stack.zig").BoundedStack;
const value_module = @import("value.zig");
const call_stack_module = @import("call_stack.zig");
const StringReference = value_module.StringReference;
const Pointer = call_stack_module.Pointer;
const Frame = call_stack_module.Frame;
const Temp = call_stack_module.Temp;
const CallStack = call_stack_module.CallStack;
const copy_frames = call_stack_module.copy_frames;

pub const Choice = struct {
    text: StringReference,
    /// Where choosing goes.
    target: Pointer,
    /// The choice point that made it (ink's sourcePath, for saves).
    source: Pointer,
    /// ink's originalThreadIndex: the thread the choice was generated in.
    original_thread: u32,
    /// The counter of the forked thread stored for it (threadAtGeneration.threadIndex).
    thread_counter: u32,
    tags_first: u32,
    snapshot: u32,
    tags_count: u16,
    invisible_default: bool,
};

pub const Snapshot = struct {
    frames_first: u32,
    frames_count: u32,
    temps_first: u32,
    temps_count: u32,
    previous_pointer: Pointer,
};

comptime {
    assert(@sizeOf(Choice) == limits.element_bytes.choice);
}

pub const Error = error{ ChoiceLimit, TagLimit, SnapshotLimit };

pub const Choices = struct {
    records: BoundedStack(Choice),
    tags: BoundedStack(StringReference),
    snapshots: BoundedStack(Snapshot),
    frames: BoundedStack(Frame),
    temps: BoundedStack(Temp),
    /// How many leading choices have their visible index set: ink sets a choice's `index`
    /// only when the host reads currentChoices, and saves write it.
    indexed_count: u32 = 0,

    pub const Fault = enum {
        ok,
        storage,
        tags_not_contiguous,
        snapshot_out_of_range,
        snapshot_ranges,
    };

    pub const Storage = struct {
        records: []Choice,
        tags: []StringReference,
        snapshots: []Snapshot,
        frames: []Frame,
        temps: []Temp,
    };

    pub fn init(storage: Storage) Choices {
        assert(storage.records.len > 0);
        assert(storage.snapshots.len >= storage.records.len or storage.snapshots.len > 0);
        return .{
            .records = .init(storage.records),
            .tags = .init(storage.tags),
            .snapshots = .init(storage.snapshots),
            .frames = .init(storage.frames),
            .temps = .init(storage.temps),
        };
    }

    pub fn clear(choices: *Choices) void {
        assert(choices.records.buffer.len > 0);
        choices.records.clear();
        choices.tags.clear();
        choices.snapshots.clear();
        choices.frames.clear();
        choices.temps.clear();
        choices.indexed_count = 0;
        assert(choices.records.is_empty());
    }

    pub fn count(choices: *const Choices) u32 {
        assert(choices.records.count <= choices.records.buffer.len);
        assert(choices.tags.count <= choices.tags.buffer.len);
        return choices.records.count;
    }

    pub fn get(choices: *const Choices, position: u32) Choice {
        assert(position < choices.records.count);
        const choice = choices.records.slice()[position];
        assert(choice.snapshot < choices.snapshots.count);
        return choice;
    }

    /// Adds a choice generated by the current thread of `stack`, forking the thread as ink
    /// does: the counter advances and the frames are stored (or shared with the last choice).
    pub fn add(
        choices: *Choices,
        stack: *CallStack,
        choice: Choice,
        tags: []const StringReference,
    ) Error!void {
        assert(!choice.target.is_null());
        if (choices.records.is_full()) return error.ChoiceLimit;
        if (tags.len > std.math.maxInt(u16)) return error.TagLimit;
        const tags_first = choices.tags.count;
        choices.tags.push_slice(tags) catch return error.TagLimit;
        errdefer choices.tags.truncate(tags_first);
        const snapshot = try choices.capture(stack);
        stack.thread_counter += 1;
        var record = choice;
        record.original_thread = stack.current_thread().counter;
        record.thread_counter = stack.thread_counter;
        record.tags_first = tags_first;
        record.tags_count = @intCast(tags.len);
        record.snapshot = snapshot;
        choices.records.push(record) catch unreachable;
        assert(choices.records.peek().?.snapshot < choices.snapshots.count);
    }

    /// The snapshot index of the current thread: the last one if it is identical, else a
    /// new copy.
    fn capture(choices: *Choices, stack: *CallStack) Error!u32 {
        assert(stack.threads.count > 0);
        const frames = stack.current_frames();
        const first_temp = frames[0].temps_first;
        const temps = stack.temps.slice()[first_temp..];
        const previous = stack.current_thread().previous_pointer;
        if (choices.snapshots.peek()) |last| {
            if (choices.same(last, frames, temps, previous)) return choices.snapshots.count - 1;
        }
        if (choices.snapshots.is_full()) return error.SnapshotLimit;
        const snapshot: Snapshot = .{
            .frames_first = choices.frames.count,
            .frames_count = @intCast(frames.len),
            .temps_first = choices.temps.count,
            .temps_count = @intCast(temps.len),
            .previous_pointer = previous,
        };
        errdefer choices.frames.truncate(snapshot.frames_first);
        errdefer choices.temps.truncate(snapshot.temps_first);
        copy_frames(&choices.frames, &choices.temps, frames, stack.temps.slice()) catch
            return error.SnapshotLimit;
        assert(choices.temps.count == snapshot.temps_first + snapshot.temps_count);
        choices.snapshots.push(snapshot) catch unreachable;
        assert(choices.snapshots.count > 0);
        return choices.snapshots.count - 1;
    }

    fn same(
        choices: *const Choices,
        snapshot: Snapshot,
        frames: []const Frame,
        temps: []const Temp,
        previous: Pointer,
    ) bool {
        assert(snapshot.frames_count > 0);
        assert(frames.len > 0);
        if (snapshot.frames_count != frames.len or snapshot.temps_count != temps.len) return false;
        if (!std.meta.eql(snapshot.previous_pointer, previous)) return false;
        const stored_temps = choices.temps.slice()[snapshot.temps_first..][0..snapshot.temps_count];
        if (!std.mem.eql(u8, std.mem.sliceAsBytes(stored_temps), std.mem.sliceAsBytes(temps))) {
            return false;
        }
        const stored = choices.frames.slice()[snapshot.frames_first..][0..snapshot.frames_count];
        for (stored, frames) |a, b| {
            // Frames are compared without their temp offsets, which differ by design.
            var left = a;
            var right = b;
            left.temps_first = 0;
            right.temps_first = 0;
            if (!std.meta.eql(left, right)) return false;
        }
        return true;
    }

    /// Makes the thread stored for `choice` the only thread of `stack` (ink's
    /// `callStack.currentThread = choice.threadAtGeneration`).
    pub fn restore(
        choices: *const Choices,
        stack: *CallStack,
        choice: Choice,
    ) error{ FrameLimit, TempLimit }!void {
        assert(choice.snapshot < choices.snapshots.count);
        const snapshot = choices.snapshots.slice()[choice.snapshot];
        const frames = choices.frames.slice()[snapshot.frames_first..][0..snapshot.frames_count];
        const temps = choices.temps.slice()[snapshot.temps_first..][0..snapshot.temps_count];
        if (frames.len > stack.frames.buffer.len) return error.FrameLimit;
        if (temps.len > stack.temps.buffer.len) return error.TempLimit;
        stack.frames.clear();
        stack.temps.clear();
        stack.threads.clear();
        // Checked above: the copies fit.
        copy_frames(&stack.frames, &stack.temps, frames, choices.temps.slice()) catch
            unreachable;
        stack.threads.push(.{
            .frame_first = 0,
            .frame_count = snapshot.frames_count,
            .counter = choice.thread_counter,
            .previous_pointer = snapshot.previous_pointer,
        }) catch unreachable;
        stack.verify();
    }

    pub fn check(choices: *const Choices) Fault {
        assert(choices.records.buffer.len > 0);
        if (choices.records.check() != .ok or choices.tags.check() != .ok) return .storage;
        var next_tag: u32 = 0;
        for (choices.records.slice()) |choice| {
            if (choice.tags_first != next_tag) return .tags_not_contiguous;
            next_tag += choice.tags_count;
            if (choice.snapshot >= choices.snapshots.count) return .snapshot_out_of_range;
        }
        if (next_tag != choices.tags.count) return .tags_not_contiguous;
        for (choices.snapshots.slice()) |snapshot| {
            const frames_end = snapshot.frames_first + snapshot.frames_count;
            const temps_end = snapshot.temps_first + snapshot.temps_count;
            if (frames_end > choices.frames.count) return .snapshot_ranges;
            if (temps_end > choices.temps.count) return .snapshot_ranges;
        }
        assert(next_tag <= choices.tags.buffer.len);
        return .ok;
    }

    pub fn verify(choices: *const Choices) void {
        assert(choices.records.buffer.len > 0);
        fault.verify(choices.check());
    }
};

const TestState = struct {
    frames: [8]Frame = undefined,
    threads: [4]call_stack_module.Thread = undefined,
    temps: [16]Temp = undefined,
    records: [4]Choice = undefined,
    tags: [8]StringReference = undefined,
    snapshots: [4]Snapshot = undefined,
    snapshot_frames: [16]Frame = undefined,
    snapshot_temps: [16]Temp = undefined,

    fn stack(state: *TestState) CallStack {
        var result = CallStack.init(&state.frames, &state.threads, &state.temps, 8);
        result.reset(.start_of(.from_int(0)));
        assert(result.depth() == 1);
        assert(result.thread_counter == 0);
        return result;
    }

    fn choices(state: *TestState) Choices {
        const result = Choices.init(.{
            .records = &state.records,
            .tags = &state.tags,
            .snapshots = &state.snapshots,
            .frames = &state.snapshot_frames,
            .temps = &state.snapshot_temps,
        });
        assert(result.count() == 0);
        assert(result.snapshots.count == 0);
        return result;
    }
};

fn test_choice(target: u32) Choice {
    assert(target < 100);
    return .{
        .text = .heap(0),
        .target = .start_of(.from_int(target)),
        .source = .start_of(.from_int(0)),
        .original_thread = 0,
        .thread_counter = 0,
        .tags_first = 0,
        .snapshot = 0,
        .tags_count = 0,
        .invisible_default = false,
    };
}

test "choices keep their tags and fork counters, and share identical snapshots" {
    // Two choices from the same thread state, one after a temp
    // changes; check tags, counters and how many snapshots were stored.
    var state: TestState = .{};
    var stack = state.stack();
    var choices = state.choices();
    try stack.temp_set(.from_int(1), .{ .integer = 1 }, true, -1);
    try choices.add(&stack, test_choice(1), &.{ .heap(4), .heap(8) });
    try choices.add(&stack, test_choice(2), &.{});
    try stack.temp_set(.from_int(1), .{ .integer = 2 }, false, -1);
    try choices.add(&stack, test_choice(3), &.{.heap(12)});
    try std.testing.expectEqual(@as(u32, 3), choices.count());
    try std.testing.expectEqual(@as(u32, 2), choices.snapshots.count);
    try std.testing.expectEqual(@as(u32, 2), choices.get(0).tags_count);
    try std.testing.expectEqual(@as(u32, 1), choices.get(0).thread_counter);
    try std.testing.expectEqual(@as(u32, 3), choices.get(2).thread_counter);
    try std.testing.expectEqual(@as(u32, 0), choices.get(2).original_thread);
    choices.verify();
}

test "choosing restores the thread the choice was made in" {
    // A choice made inside a thread brings that thread back: generate a
    // choice inside a pushed thread with its own temp, pop the thread, restore the choice.
    var state: TestState = .{};
    var stack = state.stack();
    var choices = state.choices();
    try stack.push_thread();
    try stack.push(.tunnel, 0, 0);
    try stack.temp_set(.from_int(5), .{ .integer = 42 }, true, -1);
    try choices.add(&stack, test_choice(1), &.{});
    try stack.pop(.tunnel);
    try stack.pop_thread();
    try choices.restore(&stack, choices.get(0));
    try std.testing.expectEqual(@as(u32, 1), stack.threads.count);
    try std.testing.expectEqual(@as(u32, 2), stack.depth());
    try std.testing.expectEqual(Value{ .integer = 42 }, stack.temp_get(.from_int(5), -1).?);
    try std.testing.expectEqual(choices.get(0).thread_counter, stack.current_thread().counter);
}

const Value = value_module.Value;

test "choice limits return their errors" {
    // Negative space: fill the choices, then the tags.
    var state: TestState = .{};
    var stack = state.stack();
    var choices = state.choices();
    for (0..4) |target| try choices.add(&stack, test_choice(@intCast(target)), &.{});
    try std.testing.expectError(error.ChoiceLimit, choices.add(&stack, test_choice(9), &.{}));
    choices.clear();
    const many: [9]StringReference = @splat(.heap(0));
    try std.testing.expectError(error.TagLimit, choices.add(&stack, test_choice(1), &many));
    try std.testing.expectEqual(@as(u32, 0), choices.count());
}
