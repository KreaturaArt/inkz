//! The ground-truth gate (plan P0.10, P0.4). Every case in `test/ground_truth` is replayed on
//! an engine through the engine-neutral layer and compared with what ink v1.2.1 produced. A
//! difference is allowed only if `test/divergence_ledger.zon` lists it with a reason, and a
//! ledger entry whose case now matches fails too, so stale entries get removed.
//!
//! `zig build test -Dledger-update` rewrites the ledger instead of failing: new divergences
//! are added with an automatic reason, stale ones dropped, and existing entries kept as they
//! are, so reasons edited by hand survive.

const std = @import("std");
const assert = std.debug.assert;
const build_options = @import("build_options");
const cases_directory = @import("cases.zig").cases_directory;
pub const ledger_path = "test/divergence_ledger.zon";
const file_bytes_max = 16 * 1024 * 1024;

/// Why an engine differs from ink: a known divergence (plan §1.1) or what the comparison saw.
pub const Kind = enum {
    s1,
    s2,
    s3,
    s4,
    s5,
    s6,
    s7,
    s8,
    s9,
    s10,
    s11,
    /// The engine lacks a capability the action script uses.
    unsupported,
    /// The engine returned an error where ink didn't throw, or the other way around.
    exception,
    /// The engine crashed (a panic or a signal).
    crash,
    /// Only tags differ (often S11 on the old engine).
    tags,
    /// Only whitespace inside lines differs (often S10).
    whitespace,
    /// Not classified yet.
    other,
};

pub const Entry = struct {
    case: []const u8,
    engine: []const u8,
    kind: Kind,
    reason: []const u8,
};

pub const Mismatch = struct {
    case: []const u8,
    kind: Kind,
    reason: []const u8,
};

/// The case ids (paths below `cases_directory` without `.expected`), sorted.
pub fn collect_cases(arena: std.mem.Allocator, io: std.Io) ![]const []const u8 {
    assert(cases_directory.len > 0);
    var directory = try std.Io.Dir.cwd().openDir(io, cases_directory, .{ .iterate = true });
    defer directory.close(io);
    var walker = try directory.walk(arena);
    defer walker.deinit();
    var cases: std.ArrayList([]const u8) = .empty;
    while (try walker.next(io)) |entry| {
        if (entry.kind != .file) continue;
        if (!std.mem.endsWith(u8, entry.path, ".expected")) continue;
        if (std.mem.eql(u8, entry.path, "dotnet_random.expected")) continue;
        const id = entry.path[0 .. entry.path.len - ".expected".len];
        try cases.append(arena, try arena.dupe(u8, id));
    }
    std.mem.sort([]const u8, cases.items, {}, string_less_than);
    assert(cases.items.len > 0);
    for (cases.items) |id| assert(!std.mem.endsWith(u8, id, ".expected"));
    return cases.items;
}

fn string_less_than(_: void, a: []const u8, b: []const u8) bool {
    assert(a.len > 0);
    assert(b.len > 0);
    return std.mem.order(u8, a, b) == .lt;
}

/// Replays case `id` on `engine` in a child process (`src/replay_case.zig`). A crash ends the
/// transcript with `crash: <how>`.
fn replay_isolated(
    arena: std.mem.Allocator,
    io: std.Io,
    engine: []const u8,
    id: []const u8,
) ![]const u8 {
    assert(id.len > 0);
    assert(engine.len > 0);
    const result = try std.process.run(arena, io, .{
        .argv = &.{ build_options.replay_case_path, engine, id },
        .stdout_limit = .limited(file_bytes_max),
        .stderr_limit = .limited(file_bytes_max),
    });
    switch (result.term) {
        .exited => |code| if (code == 0) return result.stdout,
        else => {},
    }
    return std.fmt.allocPrint(arena, "{s}crash: {any}\n", .{ result.stdout, result.term });
}

/// The expected transcript of case `id`, without its provenance header.
fn read_expected(arena: std.mem.Allocator, io: std.Io, id: []const u8) ![]const u8 {
    assert(id.len > 0);
    const path = try std.fmt.allocPrint(arena, "{s}/{s}.expected", .{ cases_directory, id });
    const text = try std.Io.Dir.cwd().readFileAlloc(io, path, arena, .limited(file_bytes_max));
    const header_end = std.mem.indexOfScalar(u8, text, '\n') orelse return error.MissingHeader;
    assert(std.mem.startsWith(u8, text, "# generated by tools/ink_harness"));
    assert(header_end < text.len);
    return text[header_end + 1 ..];
}

/// Null when `actual` matches `expected`; otherwise a classified difference.
pub fn compare(arena: std.mem.Allocator, expected: []const u8, actual: []const u8) !?Mismatch {
    assert(expected.len < file_bytes_max);
    if (try lines_equivalent(arena, expected, actual, .exact)) return null;
    var mismatch: Mismatch = .{ .case = "", .kind = .other, .reason = "" };
    if (std.mem.indexOf(u8, actual, "crash: ")) |at| {
        mismatch.kind = .crash;
        mismatch.reason = try arena.dupe(u8, first_line(actual[at..]));
    } else if (std.mem.indexOf(u8, actual, "\nunsupported: ")) |at| {
        const line = first_line(actual[at + 1 ..]);
        mismatch.kind = .unsupported;
        mismatch.reason = try std.fmt.allocPrint(arena, "engine lacks it: {s}", .{line});
    } else if ((std.mem.indexOf(u8, actual, "exception: ") != null) !=
        (std.mem.indexOf(u8, expected, "exception: ") != null))
    {
        mismatch.kind = .exception;
        mismatch.reason = try first_difference(arena, expected, actual);
    } else if (try lines_equivalent(arena, expected, actual, .without_tags)) {
        mismatch.kind = .tags;
        mismatch.reason = "only tags differ";
    } else if (try lines_equivalent(arena, expected, actual, .whitespace)) {
        mismatch.kind = .whitespace;
        mismatch.reason = "only whitespace inside lines differs";
    } else {
        mismatch.reason = try first_difference(arena, expected, actual);
    }
    assert(mismatch.reason.len > 0);
    return mismatch;
}

fn first_line(text: []const u8) []const u8 {
    assert(text.len < file_bytes_max);
    const end = std.mem.indexOfScalar(u8, text, '\n') orelse text.len;
    assert(end <= text.len);
    return text[0..end];
}

const Equivalence = enum { exact, without_tags, whitespace };

/// Compares line by line. `save:` lines are JSON-equivalent (key order ignored, D15).
fn lines_equivalent(
    arena: std.mem.Allocator,
    expected: []const u8,
    actual: []const u8,
    equivalence: Equivalence,
) !bool {
    assert(expected.len < file_bytes_max);
    assert(actual.len < file_bytes_max);
    var expected_lines = significant_lines(expected, equivalence);
    var actual_lines = significant_lines(actual, equivalence);
    while (true) {
        const a = expected_lines.next();
        const b = actual_lines.next();
        if (a == null or b == null) return a == null and b == null;
        if (!try line_equivalent(arena, a.?, b.?, equivalence)) return false;
    }
}

const LineIterator = struct {
    lines: std.mem.SplitIterator(u8, .scalar),
    skip_tags: bool,

    fn next(iterator: *LineIterator) ?[]const u8 {
        assert(iterator.lines.buffer.len < file_bytes_max);
        while (iterator.lines.next()) |line| {
            if (line.len == 0) continue;
            assert(std.mem.indexOfScalar(u8, line, '\n') == null);
            if (iterator.skip_tags and std.mem.startsWith(u8, line, "tags: ")) continue;
            return if (iterator.skip_tags) strip_choice_tags(line) else line;
        }
        return null;
    }
};

fn significant_lines(text: []const u8, equivalence: Equivalence) LineIterator {
    assert(text.len < file_bytes_max);
    const iterator: LineIterator = .{
        .lines = std.mem.splitScalar(u8, text, '\n'),
        .skip_tags = equivalence == .without_tags,
    };
    assert(iterator.lines.index == 0);
    return iterator;
}

/// `  0: "text" tags ["a"]` without its ` tags [...]` suffix.
fn strip_choice_tags(line: []const u8) []const u8 {
    assert(line.len > 0);
    if (!std.mem.startsWith(u8, line, "  ")) return line;
    const at = std.mem.lastIndexOf(u8, line, "\" tags [") orelse return line;
    assert(at + 1 <= line.len);
    return line[0 .. at + 1];
}

fn line_equivalent(
    arena: std.mem.Allocator,
    a: []const u8,
    b: []const u8,
    equivalence: Equivalence,
) !bool {
    assert(a.len > 0);
    assert(b.len > 0);
    if (std.mem.eql(u8, a, b)) return true;
    if (std.mem.startsWith(u8, a, "save: ") and std.mem.startsWith(u8, b, "save: ")) {
        return json_equivalent(arena, a["save: ".len..], b["save: ".len..]);
    }
    if (equivalence != .whitespace) return false;
    if (!std.mem.startsWith(u8, a, "text: ") or !std.mem.startsWith(u8, b, "text: ")) return false;
    return equal_ignoring_spaces(a, b);
}

fn equal_ignoring_spaces(a: []const u8, b: []const u8) bool {
    var index_a: usize = 0;
    var index_b: usize = 0;
    while (true) {
        assert(index_a <= a.len);
        assert(index_b <= b.len);
        while (index_a < a.len and a[index_a] == ' ') index_a += 1;
        while (index_b < b.len and b[index_b] == ' ') index_b += 1;
        if (index_a == a.len or index_b == b.len) return index_a == a.len and index_b == b.len;
        if (a[index_a] != b[index_b]) return false;
        index_a += 1;
        index_b += 1;
    }
}

fn json_equivalent(arena: std.mem.Allocator, a: []const u8, b: []const u8) !bool {
    assert(a.len < file_bytes_max);
    assert(b.len < file_bytes_max);
    const value_a = std.json.parseFromSliceLeaky(std.json.Value, arena, a, .{}) catch return false;
    const value_b = std.json.parseFromSliceLeaky(std.json.Value, arena, b, .{}) catch return false;
    return json_values_equal(value_a, value_b);
}

/// Deep equality where object key order doesn't matter. Iterative, with an explicit stack.
fn json_values_equal(a: std.json.Value, b: std.json.Value) bool {
    var pending: [256][2]std.json.Value = undefined;
    var count: u32 = 1;
    pending[0] = .{ a, b };
    var steps: u32 = 0;
    while (count > 0) : (steps += 1) {
        // Each value is visited once; a save holds far fewer than a million values.
        assert(steps < 1_000_000);
        assert(count <= pending.len);
        count -= 1;
        const left, const right = pending[count];
        if (std.meta.activeTag(left) != std.meta.activeTag(right)) return false;
        switch (left) {
            .array => |items| {
                if (items.items.len != right.array.items.len) return false;
                for (items.items, right.array.items) |x, y| {
                    if (count == pending.len) return false;
                    pending[count] = .{ x, y };
                    count += 1;
                }
            },
            .object => |object| {
                if (object.count() != right.object.count()) return false;
                var iterator = object.iterator();
                while (iterator.next()) |entry| {
                    const other = right.object.get(entry.key_ptr.*) orelse return false;
                    if (count == pending.len) return false;
                    pending[count] = .{ entry.value_ptr.*, other };
                    count += 1;
                }
            },
            .string => |text| if (!std.mem.eql(u8, text, right.string)) return false,
            .number_string => |text| if (!std.mem.eql(u8, text, right.number_string)) return false,
            else => if (!std.meta.eql(left, right)) return false,
        }
    }
    return true;
}

fn first_difference(
    arena: std.mem.Allocator,
    expected: []const u8,
    actual: []const u8,
) ![]const u8 {
    assert(!std.mem.eql(u8, expected, actual));
    var expected_lines = std.mem.splitScalar(u8, expected, '\n');
    var actual_lines = std.mem.splitScalar(u8, actual, '\n');
    var number: u32 = 1;
    while (true) : (number += 1) {
        assert(number < std.math.maxInt(u32));
        const a = expected_lines.next() orelse "<end>";
        const b = actual_lines.next() orelse "<end>";
        if (std.mem.eql(u8, a, b)) continue;
        return std.fmt.allocPrint(arena, "line {d}: expected {s} | got {s}", .{
            number, truncate(a, 80), truncate(b, 80),
        });
    }
}

fn truncate(text: []const u8, length: usize) []const u8 {
    assert(length > 0);
    const result = text[0..@min(text.len, length)];
    assert(result.len <= length);
    return result;
}

pub fn read_ledger(arena: std.mem.Allocator, io: std.Io) ![]const Entry {
    assert(ledger_path.len > 0);
    const source = try std.Io.Dir.cwd().readFileAllocOptions(
        io,
        ledger_path,
        arena,
        .limited(file_bytes_max),
        .of(u8),
        0,
    );
    var diagnostics: std.zon.parse.Diagnostics = undefined;
    return std.zon.parse.fromSlice([]const Entry, .{
        .gpa = arena,
        .arena = arena,
        .source = source,
        .diagnostics = &diagnostics,
    }) catch |err| {
        diagnostics.log(ledger_path);
        return err;
    };
}

fn find_entry(ledger: []const Entry, engine: []const u8, case: []const u8) ?Entry {
    assert(engine.len > 0);
    assert(case.len > 0);
    for (ledger) |entry| {
        if (!std.mem.eql(u8, entry.engine, engine)) continue;
        if (std.mem.eql(u8, entry.case, case)) return entry;
    }
    return null;
}

/// Writes the ledger: entries of other engines unchanged, then this engine's divergences,
/// keeping existing entries for cases that still diverge.
fn write_ledger(
    arena: std.mem.Allocator,
    io: std.Io,
    ledger: []const Entry,
    engine: []const u8,
    mismatches: []const Mismatch,
) !void {
    assert(engine.len > 0);
    for (mismatches) |mismatch| assert(mismatch.case.len > 0);
    var output: std.Io.Writer.Allocating = .init(arena);
    const writer = &output.writer;
    try writer.writeAll(
        \\// Known differences from ink v1.2.1 (plan P0.4, P0.10), one per case and engine.
        \\// `zig build test -Dledger-update` adds new ones and drops fixed ones; edit reasons by
        \\// hand, they are kept. Kinds: s1..s11 (plan §1.1), unsupported, exception, crash,
        \\// tags, whitespace, other.
        \\.{
        \\
    );
    for (ledger) |entry| {
        if (!std.mem.eql(u8, entry.engine, engine)) try write_entry(writer, entry);
    }
    for (mismatches) |mismatch| {
        const entry = find_entry(ledger, engine, mismatch.case) orelse Entry{
            .case = mismatch.case,
            .engine = engine,
            .kind = mismatch.kind,
            .reason = mismatch.reason,
        };
        try write_entry(writer, entry);
    }
    try writer.writeAll("}\n");
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = ledger_path, .data = output.written() });
}

fn write_entry(writer: *std.Io.Writer, entry: Entry) !void {
    assert(entry.case.len > 0);
    assert(entry.engine.len > 0);
    try writer.writeAll("    .{ .case = ");
    try std.zon.stringify.serialize(entry.case, .{}, writer);
    try writer.print(", .engine = \"{s}\", .kind = .{t}, .reason = ", .{
        entry.engine,
        entry.kind,
    });
    try std.zon.stringify.serialize(entry.reason, .{}, writer);
    try writer.writeAll(" },\n");
}

/// Runs every case on the old engine and checks the result against the ledger.
fn check_engine(arena: std.mem.Allocator, io: std.Io, engine: []const u8) !void {
    assert(engine.len > 0);
    const cases = try collect_cases(arena, io);
    const ledger = try read_ledger(arena, io);
    var mismatches: std.ArrayList(Mismatch) = .empty;
    for (cases) |id| {
        const expected = try read_expected(arena, io, id);
        const actual = try replay_isolated(arena, io, engine, id);
        var mismatch = try compare(arena, expected, actual) orelse continue;
        mismatch.case = id;
        try mismatches.append(arena, mismatch);
    }
    if (build_options.ledger_update) {
        try write_ledger(arena, io, ledger, engine, mismatches.items);
        return;
    }
    var problems: u32 = 0;
    for (mismatches.items) |mismatch| {
        if (find_entry(ledger, engine, mismatch.case) != null) continue;
        std.debug.print("new divergence ({s}): {s}: {t}: {s}\n", .{
            engine, mismatch.case, mismatch.kind, mismatch.reason,
        });
        problems += 1;
    }
    problems += report_stale(ledger, engine, mismatches.items);
    assert(problems <= mismatches.items.len + ledger.len);
    std.debug.print("ground truth ({s}): {d} cases, {d} ledgered divergences, {d} problems\n", .{
        engine, cases.len, mismatches.items.len, problems,
    });
    if (problems > 0) return error.GroundTruthMismatch;
}

fn report_stale(ledger: []const Entry, engine: []const u8, mismatches: []const Mismatch) u32 {
    assert(engine.len > 0);
    var stale: u32 = 0;
    for (ledger) |entry| {
        if (!std.mem.eql(u8, entry.engine, engine)) continue;
        const still_diverges = for (mismatches) |mismatch| {
            if (std.mem.eql(u8, mismatch.case, entry.case)) break true;
        } else false;
        if (still_diverges) continue;
        std.debug.print("stale ledger entry ({s}): {s} now matches ink\n", .{ engine, entry.case });
        stale += 1;
    }
    assert(stale <= ledger.len);
    return stale;
}

test "ground truth: old engine against ink v1.2.1" {
    // Goal: P0.10. Method: replay every case on the old runtime and require every difference
    // from ink to be in the ledger, and every ledger entry to still differ.
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    try check_engine(arena_state.allocator(), std.testing.io, "old");
}

test "compare classifies differences" {
    // Goal: the classification used for automatic ledger reasons. Method: one pair per kind.
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const base = "> play\ntext: \"a b\\n\"\ntags: [\"t\"]\nend\n";
    try std.testing.expectEqual(@as(?Mismatch, null), try compare(arena, base, base));
    const no_tags = "> play\ntext: \"a b\\n\"\nend\n";
    try std.testing.expectEqual(Kind.tags, (try compare(arena, base, no_tags)).?.kind);
    const spaced = "> play\ntext: \"a  b\\n\"\ntags: [\"t\"]\nend\n";
    try std.testing.expectEqual(Kind.whitespace, (try compare(arena, base, spaced)).?.kind);
    const thrown = "> play\nexception: \"Bad\"\n";
    try std.testing.expectEqual(Kind.exception, (try compare(arena, base, thrown)).?.kind);
    const gap = "> play\nunsupported: play\n";
    try std.testing.expectEqual(Kind.unsupported, (try compare(arena, base, gap)).?.kind);
    const other = "> play\ntext: \"c\\n\"\nend\n";
    try std.testing.expectEqual(Kind.other, (try compare(arena, base, other)).?.kind);
}

test "save lines compare as JSON, ignoring key order" {
    // Goal: D15 JSON-equivalent saves. Method: the same object with keys in another order.
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const a = "save: {\"a\":1,\"b\":[true,\"x\"]}\n";
    const b = "save: {\"b\":[true,\"x\"],\"a\":1}\n";
    try std.testing.expectEqual(@as(?Mismatch, null), try compare(arena, a, b));
    const c = "save: {\"b\":[true,\"y\"],\"a\":1}\n";
    try std.testing.expect(try compare(arena, a, c) != null);
}
