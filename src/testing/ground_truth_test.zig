//! The two oracle gates over every engine (plan P0.4, P0.10):
//! - ground truth: each case in `test/ground_truth`, compared with ink v1.2.1;
//! - transcripts: each fixture in `test/transcripts`, compared with the old runtime.
//! Each story runs in its own process (`src/replay_case.zig`), so a crash is a result.

const std = @import("std");
const assert = std.debug.assert;
const build_options = @import("build_options");
const oracle = @import("oracle.zig");
const cases = @import("cases.zig");
const transcripts = @import("transcripts.zig");

const file_bytes_max = 16 * 1024 * 1024;

pub fn collect_cases(arena: std.mem.Allocator, io: std.Io) ![]const []const u8 {
    assert(cases.cases_directory.len > 0);
    var directory = try std.Io.Dir.cwd().openDir(io, cases.cases_directory, .{ .iterate = true });
    defer directory.close(io);
    var walker = try directory.walk(arena);
    defer walker.deinit();
    var ids: std.ArrayList([]const u8) = .empty;
    while (try walker.next(io)) |entry| {
        if (entry.kind != .file) continue;
        if (!std.mem.endsWith(u8, entry.path, ".expected")) continue;
        // .NET reference data for unit tests, not story cases.
        if (std.mem.startsWith(u8, entry.path, "dotnet_")) continue;
        const id = entry.path[0 .. entry.path.len - ".expected".len];
        try ids.append(arena, try arena.dupe(u8, id));
    }
    std.mem.sort([]const u8, ids.items, {}, string_less_than);
    assert(ids.items.len > 0);
    for (ids.items) |id| assert(!std.mem.endsWith(u8, id, ".expected"));
    return ids.items;
}

fn string_less_than(_: void, a: []const u8, b: []const u8) bool {
    assert(a.len > 0);
    assert(b.len > 0);
    return std.mem.order(u8, a, b) == .lt;
}

/// Replays case `id` on `engine` in a child process (`src/replay_case.zig`). A crash ends the
/// transcript with `crash: <how>`.
fn replay_isolated(
    arena: std.mem.Allocator,
    io: std.Io,
    engine: []const u8,
    id: []const u8,
) ![]const u8 {
    assert(id.len > 0);
    assert(engine.len > 0);
    const result = try std.process.run(arena, io, .{
        .argv = &.{ build_options.replay_case_path, engine, id },
        .stdout_limit = .limited(file_bytes_max),
        .stderr_limit = .limited(file_bytes_max),
    });
    switch (result.term) {
        .exited => |code| if (code == 0) return result.stdout,
        else => {},
    }
    return std.fmt.allocPrint(arena, "{s}crash: {any}\n", .{ result.stdout, result.term });
}

/// The expected transcript of case `id`, without its provenance header.
fn read_expected(arena: std.mem.Allocator, io: std.Io, id: []const u8) ![]const u8 {
    assert(id.len > 0);
    const path = try std.fmt.allocPrint(arena, "{s}/{s}.expected", .{ cases.cases_directory, id });
    const text = try std.Io.Dir.cwd().readFileAlloc(io, path, arena, .limited(file_bytes_max));
    const header_end = std.mem.indexOfScalar(u8, text, '\n') orelse return error.MissingHeader;
    assert(std.mem.startsWith(u8, text, "# generated by tools/ink_harness"));
    assert(header_end < text.len);
    return text[header_end + 1 ..];
}

fn ground_truth_results(
    arena: std.mem.Allocator,
    io: std.Io,
    engine: []const u8,
) ![]const oracle.Result {
    assert(engine.len > 0);
    const ids = try collect_cases(arena, io);
    const results = try arena.alloc(oracle.Result, ids.len);
    for (ids, results) |id, *result| {
        result.* = .{
            .case = id,
            .expected = try read_expected(arena, io, id),
            .actual = try replay_isolated(arena, io, engine, id),
        };
    }
    assert(results.len == ids.len);
    return results;
}

fn transcript_results(
    arena: std.mem.Allocator,
    io: std.Io,
    engine: []const u8,
) ![]const oracle.Result {
    assert(engine.len > 0);
    const ids = try transcripts.collect_fixtures(arena, io);
    const results = try arena.alloc(oracle.Result, ids.len);
    const cwd = std.Io.Dir.cwd();
    for (ids, results) |id, *result| {
        const path = try transcripts.transcript_path(arena, id);
        result.* = .{
            .case = id,
            .expected = try cwd.readFileAlloc(io, path, arena, .limited(file_bytes_max)),
            .actual = try transcripts.render(arena, io, engine, id),
        };
    }
    assert(results.len == ids.len);
    return results;
}

test "oracle: ground truth on every engine" {
    // Goal: P0.10. Method: every difference from ink is ledgered, and every entry still holds.
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    for (cases.engines) |engine| {
        const results = try ground_truth_results(arena, std.testing.io, engine);
        const scope: oracle.Scope = .{ .engine = engine, .corpus = .ground_truth };
        try oracle.check(arena, std.testing.io, scope, results);
    }
}

test "oracle: transcripts on every engine" {
    // Goal: P0.4. Method: every difference from the old runtime's transcripts is ledgered.
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    for (cases.transcript_engines) |engine| {
        const results = try transcript_results(arena, std.testing.io, engine);
        const scope: oracle.Scope = .{ .engine = engine, .corpus = .transcripts };
        try oracle.check(arena, std.testing.io, scope, results);
    }
}
