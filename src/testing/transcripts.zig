//! The transcript corpus: every compiled fixture played on the runtime with a seeded choice
//! policy, stored in `test/transcripts/`. The oracle compares the runtime against these
//! files ("oracle: transcripts" in ground_truth_test.zig, the corpus's one replay);
//! `zig build transcripts` regenerates them.
//!
//! Each story runs in its own process (`dev replay`, src/dev.zig) with `turns_max` turns, so a
//! looping story ends with `turns_max reached` and a crashing one with `crash: <how>`.
//! A story whose turn never ends stops at the line cap with `exception: "ContinueLimit"`;
//! `overrides` lowers that cap for such stories, so their transcripts stay small.

const std = @import("std");
const assert = std.debug.assert;
const cases = @import("cases.zig");
const isolated = @import("isolated.zig");

pub const fixtures_directory = "test/fixture/compiled";
pub const transcripts_directory = "test/transcripts";
/// The choice policy and the final variables. Seed 1 makes `Next() % n` pick varied choices.
pub const actions = "play_seeded 1\nglobals\n";
const header_prefix = "# generated by `zig build transcripts` from the runtime; actions: ";

/// Actions that run before `actions` for one fixture.
const Override = struct { id: []const u8, actions: []const u8 };

/// The fixtures that need more than `actions`.
const overrides = [_]Override{
    // The story's one turn loops forever: at the default cap its transcript was 100k lines
    // (2.7 MB). 250 lines still reach the cap.
    .{ .id = "player/variable_observation", .actions = "lines_max 250\n" },
};

/// The actions fixture `id` is played with.
pub fn actions_for(arena: std.mem.Allocator, id: []const u8) ![]const u8 {
    for (overrides) |override| {
        if (std.mem.eql(u8, override.id, id)) {
            assert(override.actions.len > 0);
            assert(override.actions[override.actions.len - 1] == '\n');
            return std.mem.concat(arena, u8, &.{ override.actions, actions });
        }
    }
    return actions;
}

/// The provenance line: the actions, one per line, joined with ", ".
fn header(arena: std.mem.Allocator, played: []const u8) ![]const u8 {
    var text: std.ArrayList(u8) = .empty;
    try text.appendSlice(arena, header_prefix);
    var lines = std.mem.tokenizeScalar(u8, played, '\n');
    var first = true;
    while (lines.next()) |line| {
        if (!first) try text.appendSlice(arena, ", ");
        try text.appendSlice(arena, line);
        first = false;
    }
    try text.append(arena, '\n');
    return text.items;
}

/// Fixture paths below `fixtures_directory` without `.ink.json`, sorted.
pub fn collect_fixtures(arena: std.mem.Allocator, io: std.Io) ![]const []const u8 {
    return cases.list_sorted(arena, io, fixtures_directory, ".ink.json");
}

/// The transcript file contents for fixture `id`, played in a child process.
pub fn render(arena: std.mem.Allocator, io: std.Io, id: []const u8) ![]const u8 {
    const json = try std.fmt.allocPrint(arena, "{s}/{s}.ink.json", .{ fixtures_directory, id });
    const played = try actions_for(arena, id);
    const run = try isolated.replay(arena, io, &.{ "--json", json, "--actions", played });
    return std.mem.concat(arena, u8, &.{ try header(arena, played), run.transcript });
}

pub fn transcript_path(arena: std.mem.Allocator, id: []const u8) ![]const u8 {
    return std.fmt.allocPrint(arena, "{s}/{s}.transcript", .{ transcripts_directory, id });
}

/// Regenerates every transcript file.
pub fn write_all(arena: std.mem.Allocator, io: std.Io) !u32 {
    const fixtures = try collect_fixtures(arena, io);
    const cwd = std.Io.Dir.cwd();
    for (fixtures) |id| {
        const path = try transcript_path(arena, id);
        if (std.fs.path.dirname(path)) |directory| try cwd.createDirPath(io, directory);
        try cwd.writeFile(io, .{ .sub_path = path, .data = try render(arena, io, id) });
    }
    return @intCast(fixtures.len);
}

test "a looping story stops at the turn cap with a marker" {
    // Transcripts always end: a fixture whose choices loop back forever.
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const text = try render(arena, std.testing.io, "runtime/diverts/path_to_self");
    try std.testing.expect(std.mem.indexOf(u8, text, "turns_max reached\n") != null);
}

test "a turn that never ends stops at the lowered line cap and stays small" {
    // player/variable_observation loops within one turn; its override caps it at 250 lines.
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const id = "player/variable_observation";
    const text = try render(arena, std.testing.io, id);
    try std.testing.expect(std.mem.indexOf(u8, text, "exception: \"ContinueLimit\"\n") != null);
    try std.testing.expectEqual(@as(usize, 250), std.mem.count(u8, text, "\ntext: "));
    try std.testing.expect(text.len < 50 * 1024);
    const played = try actions_for(arena, id);
    try std.testing.expect(std.mem.startsWith(u8, played, "lines_max 250\n"));
    try std.testing.expect(std.mem.endsWith(u8, played, actions));
}
