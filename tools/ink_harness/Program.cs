// Ground-truth generator for inkz (plan D19). Commands:
//
//   compile <story.ink> <story.ink.json> [--count-all-visits]   compile like inklecate
//   random <count> <seed>...                 System.Random(seed).Next() sequences
//   paths <story.ink.json>                   every container: path, shuffle hash, flags
//   floats                                   float.ToString() for a fixed set of values
//   run <story.ink.json> <case.actions> <name>  replay host actions, print the transcript;
//                                            a missing .actions file means `play`
//
// Every text output starts with a provenance header. Strings are JSON-escaped so the files
// compare byte for byte. Nothing here depends on the clock: the story seed is always set.

using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using Ink;
using Story = Ink.Runtime.Story;
using Path = System.IO.Path;

static class Program
{
    const string InkVersion = "v1.2.1";
    const string InkCommit = "35c63e52f1d3";

    static int Main(string[] arguments)
    {
        CultureInfo.DefaultThreadCurrentCulture = CultureInfo.InvariantCulture;
        CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
        if (arguments.Length == 0) return Usage();
        switch (arguments[0])
        {
            case "compile" when arguments.Length == 3:
                return Compile(arguments[1], arguments[2], false);
            case "compile" when arguments.Length == 4 && arguments[3] == "--count-all-visits":
                return Compile(arguments[1], arguments[2], true);
            case "random" when arguments.Length >= 3:
                return RandomSequences(arguments);
            case "floats" when arguments.Length == 1:
                return Floats();
            case "paths" when arguments.Length == 2:
                return Paths(arguments[1]);
            case "run" when arguments.Length == 4:
                return Run(arguments[1], arguments[2], arguments[3]);
            default:
                return Usage();
        }
    }

    static int Usage()
    {
        Console.Error.WriteLine("usage: ink_harness compile|random|run ...");
        return 2;
    }

    public static string Provenance(string command)
    {
        var dotnet = $"{Environment.Version.Major}.{Environment.Version.Minor}";
        return $"# generated by tools/ink_harness from ink {InkVersion} ({InkCommit}) on " +
            $".NET {dotnet}; regenerate with: {command}\n";
    }

    static int Compile(string sourcePath, string outputPath, bool countAllVisits)
    {
        var fullSource = Path.GetFullPath(sourcePath);
        var fullOutput = Path.GetFullPath(outputPath);
        var errors = new List<string>();
        var previousDirectory = Directory.GetCurrentDirectory();
        // INCLUDE paths are relative to the main file, as with inklecate.
        Directory.SetCurrentDirectory(Path.GetDirectoryName(fullSource));
        try
        {
            var compiler = new Compiler(File.ReadAllText(fullSource), new Compiler.Options
            {
                sourceFilename = Path.GetFileName(fullSource),
                countAllVisits = countAllVisits,
                errorHandler = (message, type) =>
                {
                    if (type == ErrorType.Error) errors.Add(message);
                },
            });
            var story = compiler.Compile();
            if (story == null || errors.Count > 0)
            {
                foreach (var error in errors) Console.Error.WriteLine(error);
                return 1;
            }
            File.WriteAllText(fullOutput, story.ToJson(), new UTF8Encoding(true));
            return 0;
        }
        finally
        {
            Directory.SetCurrentDirectory(previousDirectory);
        }
    }

    static int RandomSequences(string[] arguments)
    {
        var count = int.Parse(arguments[1], CultureInfo.InvariantCulture);
        var output = new StringBuilder();
        output.Append(Provenance("mise run reference:random"));
        for (var index = 2; index < arguments.Length; index += 1)
        {
            var seed = int.Parse(arguments[index], CultureInfo.InvariantCulture);
            var random = new Random(seed);
            output.Append("seed ").Append(seed).Append(':');
            for (var n = 0; n < count; n += 1) output.Append(' ').Append(random.Next());
            output.Append('\n');
        }
        Console.Out.Write(output.ToString());
        return 0;
    }

    // Every container in depth-first order (content first, then named-only children by name),
    // with its path, the shuffle hash ink computes from it, its counting flags and how many
    // content items it has.
    static int Paths(string storyPath)
    {
        var story = new Story(File.ReadAllText(storyPath));
        var output = new StringBuilder();
        var name = Path.GetFileName(storyPath).Replace(".ink.json", "");
        output.Append(Provenance($"mise run reference:paths -- {name}"));
        var pending = new Stack<Ink.Runtime.Container>();
        pending.Push(story.mainContentContainer);
        while (pending.Count > 0)
        {
            var container = pending.Pop();
            var path = container.path.ToString();
            var hash = 0;
            foreach (var character in path) hash += character;
            output.Append(Transcript.Json(path)).Append(' ').Append(hash)
                .Append(container.visitsShouldBeCounted ? " visits" : "")
                .Append(container.turnIndexShouldBeCounted ? " turns" : "")
                .Append(container.countingAtStartOnly ? " start_only" : "")
                .Append(" content ").Append(container.content.Count).Append('\n');
            var children = new List<Ink.Runtime.Container>();
            foreach (var item in container.content)
            {
                if (item is Ink.Runtime.Container child) children.Add(child);
            }
            if (container.namedOnlyContent != null)
            {
                var names = new List<string>(container.namedOnlyContent.Keys);
                names.Sort(StringComparer.Ordinal);
                foreach (var key in names)
                {
                    if (container.namedOnlyContent[key] is Ink.Runtime.Container child) children.Add(child);
                }
            }
            for (var index = children.Count - 1; index >= 0; index -= 1) pending.Push(children[index]);
        }
        Console.Out.Write(output.ToString());
        return 0;
    }

    // How .NET 8 prints floats, which ink uses for float output and string conversion: each
    // line is the value's bits in hex and its InvariantCulture string.
    static int Floats()
    {
        var values = new List<float> {
            0f, -0f, 1f, -1f, 0.5f, 0.1f, 0.2f, 0.3f, 1f / 3f, 2f / 3f, 7f / 3f, 3.3f, 1000000f * 3.3f,
            10f, 100f, 1234567f, 12345678f, 123456789f, 1e7f, 1e8f, 1e14f, 1e15f, 1e16f, 1e20f,
            1e-4f, 1e-5f, 1e-6f, 0.000123f, 1.5e-7f, 3.4028235e38f, 1.17549435e-38f, 1e-45f,
            float.NaN, float.PositiveInfinity, float.NegativeInfinity, 16777216f, 16777217f,
            2.5f, -2.5f, 0.15f, 123.456f, 99999.99f, 0.0001f, 4.2e15f, 4.25e-5f, 255f / 256f,
            1e9f, 1e10f, 1e11f, 1e12f, 1e13f, 1.5e9f, 123456789012f, 9.99e13f, 1.25e-4f,
        };
        var output = new StringBuilder();
        output.Append(Provenance("mise run reference:floats"));
        foreach (var value in values)
        {
            var bits = BitConverter.SingleToInt32Bits(value);
            output.Append(bits.ToString("x8")).Append(' ')
                .Append(value.ToString(CultureInfo.InvariantCulture)).Append('\n');
        }
        Console.Out.Write(output.ToString());
        return 0;
    }

    static int Run(string storyPath, string actionsPath, string name)
    {
        var json = File.ReadAllText(storyPath);
        var transcript = new Transcript(json);
        var actions = File.Exists(actionsPath) ? File.ReadAllLines(actionsPath) : new[] { "play" };
        var output = new StringBuilder();
        output.Append(Provenance($"mise run reference:expected -- {name}"));
        try
        {
            foreach (var raw in actions)
            {
                var line = raw.Trim();
                if (line.Length == 0 || line.StartsWith("#")) continue;
                output.Append("> ").Append(line).Append('\n');
                transcript.Apply(line, output);
            }
        }
        catch (StopTranscript)
        {
            // The exception is already in the transcript.
        }
        Console.Out.Write(output.ToString());
        return 0;
    }
}
